// Command bindingsgen generates explicit adapters for the assets Loom service.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
)

var explicitMethods = map[string]bool{
	"GetAPIAssetsV2StaticByAssetID":           true,
	"PostAPIAssetsV2UserAssets":               true,
	"PostAPIV1AssetsUserAssets":               true,
	"PostAPIV1AssetsUserAssetsServer":         true,
	"PostAPIV1WorkspacesBySlugAssets":         true,
	"GetAPIV1WorkspacesBySlugAssetsByAssetID": true,
}

type importedPackage struct {
	name string
	path string
}

func main() {
	output := flag.String("output", "service_bindings.go", "output file relative to the current directory")
	check := flag.Bool("check", false, "fail if the output file is stale")
	protocolOutput := flag.String("protocol-output", "", "optional generated cmd/system protocol helper output")
	flag.Parse()

	generated, err := generate()
	if err != nil {
		fail("generate assets service bindings: %v", err)
	}
	if *check {
		current, err := os.ReadFile(*output)
		if err != nil {
			fail("read generated bindings %s: %v", *output, err)
		}
		if !bytes.Equal(current, generated) {
			fail("%s is stale; run go generate ./internal/assets", *output)
		}
		if *protocolOutput != "" {
			protocol, err := generateProtocolMounts()
			if err != nil {
				fail("generate assets protocol mounts: %v", err)
			}
			currentProtocol, err := os.ReadFile(*protocolOutput)
			if err != nil {
				fail("read generated protocol mounts %s: %v", *protocolOutput, err)
			}
			if !bytes.Equal(currentProtocol, protocol) {
				fail("%s is stale; run go generate ./assetslifecycle/design", *protocolOutput)
			}
		}
		return
	}
	if err := os.WriteFile(*output, generated, 0o644); err != nil {
		fail("write generated bindings %s: %v", *output, err)
	}
	if *protocolOutput != "" {
		protocol, err := generateProtocolMounts()
		if err != nil {
			fail("generate assets protocol mounts: %v", err)
		}
		if err := os.WriteFile(*protocolOutput, protocol, 0o644); err != nil {
			fail("write generated protocol mounts %s: %v", *protocolOutput, err)
		}
	}
}

func generate() ([]byte, error) {
	fset := token.NewFileSet()
	servicePath, err := serviceInterfacePath()
	if err != nil {
		return nil, err
	}
	file, err := parser.ParseFile(fset, servicePath, nil, parser.AllErrors)
	if err != nil {
		return nil, err
	}
	imports := importedPackages(file)
	service := findServiceInterface(file)
	if service == nil {
		return nil, fmt.Errorf("Service interface not found in %s", servicePath)
	}

	usedImports := map[string]importedPackage{}
	methods := make([]string, 0, len(service.Methods.List))
	operationNames := make([]string, 0, len(service.Methods.List))
	for _, field := range service.Methods.List {
		if len(field.Names) != 1 {
			return nil, fmt.Errorf("unexpected embedded or unnamed Service field")
		}
		name := field.Names[0].Name
		operationNames = append(operationNames, name)
		if explicitMethods[name] {
			continue
		}
		methodType, ok := field.Type.(*ast.FuncType)
		if !ok {
			return nil, fmt.Errorf("Service.%s is not a method", name)
		}
		method, imports, err := renderMethod(name, methodType, imports)
		if err != nil {
			return nil, err
		}
		for _, imported := range imports {
			usedImports[imported.name] = imported
		}
		methods = append(methods, method)
	}
	if len(methods) == 0 {
		return nil, fmt.Errorf("Service interface has no methods to generate")
	}
	for name := range explicitMethods {
		if !methodExists(service, name) {
			return nil, fmt.Errorf("explicit implementation %s is absent from generated Service interface", name)
		}
	}

	var source bytes.Buffer
	source.WriteString("// Code generated by bindingsgen from the Loom Service interface. DO NOT EDIT.\n")
	source.WriteString("//go:generate go run ./bindingsgen -output service_bindings.go\n\n")
	source.WriteString("package assets\n\nimport (\n\t\"context\"\n\t\"encoding/json\"\n\t\"errors\"\n\t\"fmt\"\n\t\"io\"\n\t\"reflect\"\n\n")
	source.WriteString("\tapi \"github.com/CaliLuke/go-plane/assetslifecycle/gen/plane_internal_django_migration_api\"\n")
	source.WriteString("\t\"github.com/CaliLuke/go-plane/internal/djangoapi\"\n")
	for _, imported := range sortedImports(usedImports) {
		source.WriteString("\t" + imported.name + " " + strconv.Quote(imported.path) + "\n")
	}
	source.WriteString(")\n\n")
	source.WriteString(`type BindingResultTypeError struct {
	Method   string
	Expected string
	Actual   string
}

func (err *BindingResultTypeError) Error() string {
	return fmt.Sprintf("assets lifecycle %s returned %s; expected %s", err.Method, err.Actual, err.Expected)
}

func castBindingResult[T any](method string, result any) (T, error) {
	var zero T
	if result == nil {
		resultType := reflect.TypeOf(zero)
		if resultType == nil || !isNilable(resultType.Kind()) {
			return zero, &BindingResultTypeError{Method: method, Expected: fmt.Sprintf("%T", zero), Actual: "<nil>"}
		}
		return zero, nil
	}
	typed, ok := result.(T)
	if !ok {
		return zero, &BindingResultTypeError{Method: method, Expected: fmt.Sprintf("%T", zero), Actual: fmt.Sprintf("%T", result)}
	}
	return typed, nil
}

func isNilable(kind reflect.Kind) bool {
	switch kind {
	case reflect.Chan, reflect.Func, reflect.Interface, reflect.Map, reflect.Pointer, reflect.Slice:
		return true
	default:
		return false
	}
}

`)
	statusTypes := findStatusTypes(file, operationNames)
	source.WriteString(renderErrorMapper(statusTypes))
	for _, method := range methods {
		source.WriteString(method)
		source.WriteString("\n\n")
	}
	source.WriteString("var _ api.Service = (*LifecycleService)(nil)\n")
	return format.Source(source.Bytes())
}

func findStatusTypes(file *ast.File, operations []string) map[string]map[string]statusType {
	statusTypes := make(map[string]map[string]statusType, len(operations))
	for _, operation := range operations {
		statusTypes[operation] = make(map[string]statusType)
		for _, declaration := range file.Decls {
			general, ok := declaration.(*ast.GenDecl)
			if !ok || general.Tok != token.TYPE {
				continue
			}
			for _, spec := range general.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				suffix := strings.TrimPrefix(typeSpec.Name.Name, operation+"Status")
				if suffix == typeSpec.Name.Name || len(suffix) != 3 {
					continue
				}
				if _, err := strconv.Atoi(suffix); err != nil {
					continue
				}
				statusTypes[operation][suffix] = statusType{name: typeSpec.Name.Name, pointerReceiver: hasPointerErrorReceiver(file, typeSpec.Name.Name)}
			}
		}
	}
	return statusTypes
}

type statusType struct {
	name            string
	pointerReceiver bool
}

func hasPointerErrorReceiver(file *ast.File, typeName string) bool {
	for _, declaration := range file.Decls {
		method, ok := declaration.(*ast.FuncDecl)
		if !ok || method.Name.Name != "Error" || method.Recv == nil || len(method.Recv.List) != 1 {
			continue
		}
		switch receiver := method.Recv.List[0].Type.(type) {
		case *ast.StarExpr:
			if identifier, ok := receiver.X.(*ast.Ident); ok && identifier.Name == typeName {
				return true
			}
		case *ast.Ident:
			if receiver.Name == typeName {
				return false
			}
		}
	}
	return false
}

func renderErrorMapper(statusTypes map[string]map[string]statusType) string {
	var source strings.Builder
	source.WriteString(`// mapAssetsLifecycleError converts source-shaped errors to the operation-specific
// response types required by Loom's generated encoder.
func mapAssetsLifecycleError(operation string, err error) error {
	status := 500
	body := any(map[string]any{"error": "Something went wrong please try again later"})
	var response *djangoapi.HTTPError
	if errors.As(err, &response) {
		status = response.Status
		body = response.Body
	}
	encoded, marshalErr := json.Marshal(body)
	if marshalErr != nil {
		status = 500
		encoded, _ = json.Marshal(map[string]any{"error": "Something went wrong please try again later"})
	}
	switch operation {
`)
	operations := make([]string, 0, len(statusTypes))
	for operation := range statusTypes {
		operations = append(operations, operation)
	}
	sort.Strings(operations)
	for _, operation := range operations {
		fmt.Fprintf(&source, "\tcase %q:\n\t\tswitch status {\n", operation)
		statuses := make([]string, 0, len(statusTypes[operation]))
		for status := range statusTypes[operation] {
			statuses = append(statuses, status)
		}
		sort.Strings(statuses)
		for _, status := range statuses {
			typeInfo := statusTypes[operation][status]
			if typeInfo.pointerReceiver {
				fmt.Fprintf(&source, "\t\tcase %s:\n\t\t\tresult := &api.%s{}\n\t\t\tif json.Unmarshal(encoded, result) == nil {\n\t\t\t\treturn result\n\t\t\t}\n", status, typeInfo.name)
			} else {
				fmt.Fprintf(&source, "\t\tcase %s:\n\t\t\tresult := api.%s{}\n\t\t\tif json.Unmarshal(encoded, &result) == nil {\n\t\t\t\treturn result\n\t\t\t}\n", status, typeInfo.name)
			}
		}
		if typeInfo, ok := statusTypes[operation]["500"]; ok {
			if typeInfo.pointerReceiver {
				fmt.Fprintf(&source, "\t\tdefault:\n\t\t\tresult := &api.%s{}\n\t\t\tif json.Unmarshal(encoded, result) == nil {\n\t\t\t\treturn result\n\t\t\t}\n", typeInfo.name)
			} else {
				fmt.Fprintf(&source, "\t\tdefault:\n\t\t\tresult := api.%s{}\n\t\t\tif json.Unmarshal(encoded, &result) == nil {\n\t\t\t\treturn result\n\t\t\t}\n", typeInfo.name)
			}
		}
		source.WriteString("\t\t}\n")
	}
	source.WriteString(`	}
	return err
}

`)
	return source.String()
}

func serviceInterfacePath() (string, error) {
	_, sourceFile, _, ok := runtime.Caller(0)
	if !ok {
		return "", fmt.Errorf("locate bindingsgen source file")
	}
	absolute, err := filepath.Abs(sourceFile)
	if err != nil {
		return "", err
	}
	return filepath.Clean(filepath.Join(filepath.Dir(absolute), "../../../assetslifecycle/gen/plane_internal_django_migration_api/service.go")), nil
}

type assetsLifecycleOperation struct {
	Method          string   `json:"method"`
	Path            string   `json:"path"`
	Authentication  []string `json:"authentication"`
	ProtocolMethods []string `json:"protocol_methods"`
}

type assetsLifecycleInvalidRoute struct {
	Path           string   `json:"path"`
	InvalidMethods []string `json:"invalid_methods"`
}

type generatedMount struct {
	Method string
	Verb   string
	Path   string
}

func generateProtocolMounts() ([]byte, error) {
	_, sourceFile, _, ok := runtime.Caller(0)
	if !ok {
		return nil, fmt.Errorf("locate bindingsgen source file")
	}
	repoRoot := filepath.Clean(filepath.Join(filepath.Dir(sourceFile), "../../../../../"))
	manifestPath := filepath.Join(repoRoot, "docs/go-backend-replacement/assets-lifecycle-manifest.json")
	decisionPath := filepath.Join(repoRoot, "docs/go-backend-replacement/decisions/ASSET-001-invalid-methods.json")
	var manifest struct {
		Operations map[string]assetsLifecycleOperation `json:"operations"`
	}
	if err := readJSON(manifestPath, &manifest); err != nil {
		return nil, err
	}
	var decision struct {
		Routes []assetsLifecycleInvalidRoute `json:"routes"`
	}
	if err := readJSON(decisionPath, &decision); err != nil {
		return nil, err
	}
	invalidGet := make(map[string]struct{})
	for _, route := range decision.Routes {
		for _, method := range route.InvalidMethods {
			if method == "GET" {
				invalidGet[route.Path] = struct{}{}
			}
		}
	}

	serverPath := filepath.Join(repoRoot, "apps/go-api/assetslifecycle/gen/http/plane_internal_django_migration_api/server/server.go")
	mounts, err := readGeneratedMounts(serverPath)
	if err != nil {
		return nil, err
	}
	mountByPath := make(map[string]generatedMount)
	for _, mount := range mounts {
		if mount.Verb == "GET" {
			mountByPath[mount.Path] = mount
		}
	}
	var eligible []generatedMount
	for _, operation := range manifest.Operations {
		if operation.Method != "GET" || strings.HasPrefix(operation.Path, "/api/v1/") || !containsString(operation.Authentication, "session") || !containsString(operation.ProtocolMethods, "HEAD") {
			continue
		}
		if _, excluded := invalidGet[operation.Path]; excluded {
			continue
		}
		mount, exists := mountByPath[operation.Path]
		if !exists {
			return nil, fmt.Errorf("source-session GET %s is absent from generated Loom server mounts", operation.Path)
		}
		eligible = append(eligible, mount)
	}
	sort.Slice(eligible, func(i, j int) bool { return eligible[i].Path < eligible[j].Path })

	var source bytes.Buffer
	source.WriteString("// Code generated by bindingsgen from the assets manifest and generated Loom server. DO NOT EDIT.\n\n")
	source.WriteString("package main\n\nimport (\n\t\"net/http\"\n\n")
	source.WriteString("assetslifecyclesvr \"github.com/CaliLuke/go-plane/assetslifecycle/gen/http/plane_internal_django_migration_api/server\"\n")
	source.WriteString("loomhttp \"github.com/CaliLuke/loom/http\"\n)\n\n")
	source.WriteString("type assetsLifecycleMountedRoute struct { Method, Path string }\n\n")
	source.WriteString("func assetsLifecycleMountedRoutes(server *assetslifecyclesvr.Server) map[assetsLifecycleMountedRoute]struct{} {\n")
	source.WriteString("\troutes := make(map[assetsLifecycleMountedRoute]struct{}, len(server.Mounts))\n\tfor _, mount := range server.Mounts {\n\t\troutes[assetsLifecycleMountedRoute{Method: mount.Verb, Path: mount.Pattern}] = struct{}{}\n\t}\n\treturn routes\n}\n\n")
	source.WriteString("func mountAssetsLifecycleDerivedHeads(mux loomhttp.Muxer, server *assetslifecyclesvr.Server) map[string]struct{} {\n")
	source.WriteString("\tderived := make(map[string]struct{})\n")
	source.WriteString("\tfor _, mount := range server.Mounts {\n\t\tif mount.Verb != http.MethodGet { continue }\n\t\tswitch mount.Method {\n")
	for _, mount := range eligible {
		source.WriteString("\t\tcase " + strconv.Quote(mount.Method) + ":\n")
		source.WriteString("\t\t\tif mount.Pattern == " + strconv.Quote(mount.Path) + " { loomhttp.MountDerivedHead(mux, mount.Pattern, server." + mount.Method + "); derived[mount.Pattern] = struct{}{} }\n")
	}
	source.WriteString("\t\t}\n\t}\n\treturn derived\n}\n")
	return format.Source(source.Bytes())
}

func readJSON(filename string, destination any) error {
	data, err := os.ReadFile(filename)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(data, destination); err != nil {
		return fmt.Errorf("parse %s: %w", filename, err)
	}
	return nil
}

func containsString(values []string, target string) bool {
	for _, value := range values {
		if value == target {
			return true
		}
	}
	return false
}

func readGeneratedMounts(filename string) ([]generatedMount, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filename, nil, parser.AllErrors)
	if err != nil {
		return nil, err
	}
	var mounts []generatedMount
	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if !ok || function.Name.Name != "New" || function.Body == nil {
			continue
		}
		ast.Inspect(function.Body, func(node ast.Node) bool {
			literal, ok := node.(*ast.KeyValueExpr)
			if !ok || renderExpr(literal.Key) != "Mounts" {
				return true
			}
			list, ok := literal.Value.(*ast.CompositeLit)
			if !ok {
				return true
			}
			for _, element := range list.Elts {
				entry, ok := element.(*ast.CompositeLit)
				if !ok || len(entry.Elts) != 3 {
					continue
				}
				values := make([]string, 3)
				for i, value := range entry.Elts {
					basic, ok := value.(*ast.BasicLit)
					if !ok {
						return true
					}
					parsed, err := strconv.Unquote(basic.Value)
					if err != nil {
						return true
					}
					values[i] = parsed
				}
				mounts = append(mounts, generatedMount{Method: values[0], Verb: values[1], Path: values[2]})
			}
			return false
		})
	}
	if len(mounts) == 0 {
		return nil, fmt.Errorf("generated Loom server %s has no mount metadata", filename)
	}
	return mounts, nil
}

func findServiceInterface(file *ast.File) *ast.InterfaceType {
	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.TYPE {
			continue
		}
		for _, spec := range general.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok || typeSpec.Name.Name != "Service" {
				continue
			}
			service, _ := typeSpec.Type.(*ast.InterfaceType)
			return service
		}
	}
	return nil
}

func methodExists(service *ast.InterfaceType, name string) bool {
	for _, field := range service.Methods.List {
		if len(field.Names) == 1 && field.Names[0].Name == name {
			return true
		}
	}
	return false
}

func importedPackages(file *ast.File) map[string]importedPackage {
	packages := make(map[string]importedPackage, len(file.Imports))
	for _, spec := range file.Imports {
		importPath, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			continue
		}
		name := path.Base(importPath)
		if spec.Name != nil {
			name = spec.Name.Name
		}
		packages[name] = importedPackage{name: name, path: importPath}
	}
	return packages
}

func renderMethod(name string, method *ast.FuncType, imported map[string]importedPackage) (string, []importedPackage, error) {
	if method.Params == nil || len(method.Params.List) < 2 || len(method.Params.List) > 3 {
		return "", nil, fmt.Errorf("Service.%s has unsupported parameter list", name)
	}
	if renderExpr(method.Params.List[0].Type) != "context.Context" {
		return "", nil, fmt.Errorf("Service.%s first parameter is not context.Context", name)
	}
	payload, ok := method.Params.List[1].Type.(*ast.StarExpr)
	if !ok {
		return "", nil, fmt.Errorf("Service.%s payload is not a pointer", name)
	}
	payloadName, ok := payload.X.(*ast.Ident)
	if !ok {
		return "", nil, fmt.Errorf("Service.%s payload type is not local to generated API package", name)
	}
	args := "ctx context.Context, payload *api." + payloadName.Name
	body := "nil"
	if len(method.Params.List) == 3 {
		if renderExpr(method.Params.List[2].Type) != "io.ReadCloser" {
			return "", nil, fmt.Errorf("Service.%s third parameter is not io.ReadCloser", name)
		}
		args += ", body io.ReadCloser"
		body = "body"
	}

	if method.Results == nil || len(method.Results.List) == 0 {
		return "", nil, fmt.Errorf("Service.%s has no result list", name)
	}
	if len(method.Results.List) == 1 && renderExpr(method.Results.List[0].Type) == "error" {
		return fmt.Sprintf("func (service *LifecycleService) %s(%s) error {\n\t_, err := service.invoke(ctx, %q, payload, %s)\n\tif err != nil {\n\t\treturn mapAssetsLifecycleError(%q, err)\n\t}\n\treturn nil\n}", name, args, name, body, name), nil, nil
	}
	if len(method.Results.List) != 2 || renderExpr(method.Results.List[1].Type) != "error" {
		return "", nil, fmt.Errorf("Service.%s has unsupported result list", name)
	}
	resultType, resultImports, err := renderResultType(method.Results.List[0].Type, imported)
	if err != nil {
		return "", nil, fmt.Errorf("Service.%s result: %w", name, err)
	}
	methodSource := fmt.Sprintf("func (service *LifecycleService) %s(%s) (%s, error) {\n\tresult, err := service.invoke(ctx, %q, payload, %s)\n\tif err != nil {\n\t\treturn nil, mapAssetsLifecycleError(%q, err)\n\t}\n\treturn castBindingResult[%s](%q, result)\n}", name, args, resultType, name, body, name, resultType, name)
	return methodSource, resultImports, nil
}

func renderResultType(expr ast.Expr, imported map[string]importedPackage) (string, []importedPackage, error) {
	used := map[string]importedPackage{}
	var render func(ast.Expr) (string, error)
	render = func(expr ast.Expr) (string, error) {
		switch value := expr.(type) {
		case *ast.Ident:
			if value.Name == "any" || value.Name == "error" || value.Name == "bool" || value.Name == "string" || value.Name == "int" || value.Name == "int64" || value.Name == "float64" {
				return value.Name, nil
			}
			return "api." + value.Name, nil
		case *ast.StarExpr:
			inner, err := render(value.X)
			return "*" + inner, err
		case *ast.ArrayType:
			inner, err := render(value.Elt)
			return "[]" + inner, err
		case *ast.MapType:
			key, err := render(value.Key)
			if err != nil {
				return "", err
			}
			item, err := render(value.Value)
			return "map[" + key + "]" + item, err
		case *ast.SelectorExpr:
			alias, ok := value.X.(*ast.Ident)
			if !ok {
				return "", fmt.Errorf("unsupported selector base %T", value.X)
			}
			if sourceImport, ok := imported[alias.Name]; ok {
				used[alias.Name] = sourceImport
			} else if alias.Name != "api" {
				return "", fmt.Errorf("selector package %q is not imported by service source", alias.Name)
			}
			return alias.Name + "." + value.Sel.Name, nil
		case *ast.InterfaceType:
			if len(value.Methods.List) == 0 {
				return "any", nil
			}
			return "", fmt.Errorf("nonempty interface result is unsupported")
		case *ast.IndexExpr:
			base, err := render(value.X)
			if err != nil {
				return "", err
			}
			index, err := render(value.Index)
			return base + "[" + index + "]", err
		case *ast.IndexListExpr:
			base, err := render(value.X)
			if err != nil {
				return "", err
			}
			args := make([]string, 0, len(value.Indices))
			for _, arg := range value.Indices {
				item, err := render(arg)
				if err != nil {
					return "", err
				}
				args = append(args, item)
			}
			return base + "[" + strings.Join(args, ", ") + "]", nil
		default:
			return "", fmt.Errorf("unsupported type expression %T", expr)
		}
	}
	result, err := render(expr)
	items := make([]importedPackage, 0, len(used))
	for _, item := range used {
		items = append(items, item)
	}
	return result, items, err
}

func renderExpr(expr ast.Expr) string {
	var buffer bytes.Buffer
	if err := format.Node(&buffer, token.NewFileSet(), expr); err != nil {
		return ""
	}
	return buffer.String()
}

func sortedImports(packages map[string]importedPackage) []importedPackage {
	items := make([]importedPackage, 0, len(packages))
	for _, item := range packages {
		items = append(items, item)
	}
	sort.Slice(items, func(i, j int) bool { return items[i].name < items[j].name })
	return items
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
