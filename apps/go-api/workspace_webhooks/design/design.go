// Package design defines the workspace-webhook HTTP contract.
//
//go:generate go tool loom gen github.com/CaliLuke/go-plane/workspace_webhooks/design --output ..
package design

import . "github.com/CaliLuke/loom/dsl"

var webhook = Type("Webhook", func() {
	Attribute("id", String, func() { Format(FormatUUID) })
	Attribute("workspace", String, func() { Format(FormatUUID) })
	Attribute("created_at", String, func() { Format(FormatDateTime) })
	Attribute("updated_at", String, func() { Format(FormatDateTime) })
	Attribute("created_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("updated_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("deleted_at", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("url", String, func() { MaxLength(1024) })
	Attribute("is_active", Boolean)
	Attribute("secret_key", String, func() { MaxLength(255) })
	Attribute("project", Boolean)
	Attribute("issue", Boolean)
	Attribute("module", Boolean)
	Attribute("cycle", Boolean)
	Attribute("issue_comment", Boolean)
	Attribute("is_internal", Boolean)
	Attribute("version", String, func() { MaxLength(50) })
	Required("id", "workspace", "created_at", "updated_at", "created_by", "updated_by", "deleted_at", "url", "is_active", "secret_key", "project", "issue", "module", "cycle", "issue_comment", "is_internal", "version")
})

var webhookCreateRequest = Type("WebhookCreateRequest", func() { webhookFields() })
var webhookPatchRequest = Type("WebhookPatchRequest", func() { webhookFields() })

var webhookLog = Type("WebhookLog", func() {
	Attribute("id", String, func() { Format(FormatUUID) })
	Attribute("workspace", String, func() { Format(FormatUUID) })
	Attribute("created_at", String, func() { Format(FormatDateTime) })
	Attribute("updated_at", String, func() { Format(FormatDateTime) })
	Attribute("created_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("updated_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("deleted_at", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("webhook", String, func() { Format(FormatUUID) })
	Attribute("event_type", String, func() { Nullable(); MaxLength(255) })
	Attribute("request_method", String, func() { Nullable(); MaxLength(10) })
	Attribute("request_headers", String, func() { Nullable() })
	Attribute("request_body", String, func() { Nullable() })
	Attribute("response_status", String, func() { Nullable() })
	Attribute("response_headers", String, func() { Nullable() })
	Attribute("response_body", String, func() { Nullable() })
	Attribute("retry_count", Int)
	Required("id", "workspace", "created_at", "updated_at", "created_by", "updated_by", "deleted_at", "webhook", "event_type", "request_method", "request_headers", "request_body", "response_status", "response_headers", "response_body", "retry_count")
})

var webhookUnauthenticated = Type("WebhookUnauthenticated", func() { Attribute("detail", String); Required("detail") })
var webhookForbidden = Type("WebhookForbidden", func() {
	Attribute("error", String, func() { Meta("struct:field:name", "Message") })
	Required("error")
})
var webhookNotFound = Type("WebhookNotFound", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })
var webhookMethodNotAllowed = Type("WebhookMethodNotAllowed", func() { Attribute("detail", String); Required("detail") })
var webhookConflict = Type("WebhookConflict", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })
var webhookInternal = Type("WebhookInternal", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })
var webhookInvalid = Type("WebhookInvalid", func() {
	Attribute("error", String, func() { Meta("struct:field:name", "Message") })
	Attribute("url", ArrayOf(String))
	Attribute("is_active", ArrayOf(String))
	Attribute("project", ArrayOf(String))
	Attribute("issue", ArrayOf(String))
	Attribute("module", ArrayOf(String))
	Attribute("cycle", ArrayOf(String))
	Attribute("issue_comment", ArrayOf(String))
	Attribute("is_internal", ArrayOf(String))
	Attribute("version", ArrayOf(String))
	Attribute("created_by", ArrayOf(String))
	Attribute("non_field_errors", ArrayOf(String))
})

var webhookSessionCookie = APIKeySecurity("webhook_session_cookie", func() { Description("Plane Django session cookie.") })
var _ = API("Plane Workspace Webhooks API", func() {
	Meta("http:generate", "all")
	Title("Plane Workspace Webhooks API")
	Description("Session-authenticated workspace webhook endpoints.")
	Version("1.0.0")
	Meta("openapi:version", "3.1")
	HTTP(func() {
		Consumes("application/json", "application/x-www-form-urlencoded", "multipart/form-data")
		Produces("application/json")
	})
})

var _ = Service("workspace_webhooks", func() {
	Description("Manages workspace webhooks and their delivery logs.")
	HTTP(func() { RuntimeCORS() })
	Method("list", func() {
		Security(webhookSessionCookie)
		Payload(func() {
			webhookSessionPayload()
			Attribute("slug", String)
			Attribute("search", String)
			Required("slug")
		})
		Result(ArrayOf(webhook))
		Error("unauthenticated", webhookUnauthenticated)
		Error("forbidden", webhookForbidden)
		Error("internal_error", webhookInternal, func() { Fault() })
		HTTP(func() {
			GET("/api/workspaces/{slug}/webhooks/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("search")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("create", func() {
		Security(webhookSessionCookie)
		Payload(func() {
			webhookSessionPayload()
			Attribute("slug", String)
			Required("slug")
		})
		Result(webhook)
		Error("unauthenticated", webhookUnauthenticated)
		Error("forbidden", webhookForbidden)
		Error("invalid", webhookInvalid)
		Error("conflict", webhookConflict)
		Error("internal_error", webhookInternal, func() { Fault() })
		HTTP(func() {
			SkipRequestBodyEncodeDecode()
			OpenAPIRequestBodyTypes(webhookCreateRequest, []string{"application/json", "application/x-www-form-urlencoded", "multipart/form-data"}, true)
			POST("/api/workspaces/{slug}/webhooks/")
			Cookie("session_id:session-id")
			Param("slug")
			Response(StatusCreated)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("invalid", StatusBadRequest)
			Response("conflict", StatusConflict)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("patch_collection", func() {
		Security(webhookSessionCookie)
		Payload(func() { webhookSessionPayload(); Attribute("slug", String); Required("slug") })
		Error("unauthenticated", webhookUnauthenticated)
		Error("forbidden", webhookForbidden)
		Error("method_not_allowed", webhookMethodNotAllowed)
		Error("internal_error", webhookInternal, func() { Fault() })
		HTTP(func() {
			PATCH("/api/workspaces/{slug}/webhooks/")
			Cookie("session_id:session-id")
			Param("slug")
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("method_not_allowed", StatusMethodNotAllowed)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("delete_collection", func() {
		Security(webhookSessionCookie)
		Payload(func() { webhookSessionPayload(); Attribute("slug", String); Required("slug") })
		Error("unauthenticated", webhookUnauthenticated)
		Error("forbidden", webhookForbidden)
		Error("method_not_allowed", webhookMethodNotAllowed)
		Error("internal_error", webhookInternal, func() { Fault() })
		HTTP(func() {
			DELETE("/api/workspaces/{slug}/webhooks/")
			Cookie("session_id:session-id")
			Param("slug")
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("method_not_allowed", StatusMethodNotAllowed)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("detail", func() {
		Security(webhookSessionCookie)
		Payload(func() {
			webhookSessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Required("slug", "pk")
		})
		Result(webhook)
		Error("unauthenticated", webhookUnauthenticated)
		Error("forbidden", webhookForbidden)
		Error("not_found", webhookNotFound)
		Error("internal_error", webhookInternal, func() { Fault() })
		HTTP(func() {
			GET("/api/workspaces/{slug}/webhooks/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("patch_detail", func() {
		Security(webhookSessionCookie)
		Payload(func() {
			webhookSessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Required("slug", "pk")
		})
		Result(webhook)
		Error("unauthenticated", webhookUnauthenticated)
		Error("forbidden", webhookForbidden)
		Error("not_found", webhookNotFound)
		Error("invalid", webhookInvalid)
		Error("internal_error", webhookInternal, func() { Fault() })
		HTTP(func() {
			SkipRequestBodyEncodeDecode()
			OpenAPIRequestBodyTypes(webhookPatchRequest, []string{"application/json", "application/x-www-form-urlencoded", "multipart/form-data"}, false)
			PATCH("/api/workspaces/{slug}/webhooks/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("invalid", StatusBadRequest)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("delete_detail", func() {
		Security(webhookSessionCookie)
		Payload(func() {
			webhookSessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Required("slug", "pk")
		})
		Error("unauthenticated", webhookUnauthenticated)
		Error("forbidden", webhookForbidden)
		Error("not_found", webhookNotFound)
		Error("internal_error", webhookInternal, func() { Fault() })
		HTTP(func() {
			DELETE("/api/workspaces/{slug}/webhooks/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusNoContent)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("regenerate", func() {
		Security(webhookSessionCookie)
		Payload(func() {
			webhookSessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Required("slug", "pk")
		})
		Result(webhook)
		Error("unauthenticated", webhookUnauthenticated)
		Error("forbidden", webhookForbidden)
		Error("not_found", webhookNotFound)
		Error("internal_error", webhookInternal, func() { Fault() })
		HTTP(func() {
			POST("/api/workspaces/{slug}/webhooks/{pk}/regenerate/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("logs", func() {
		Security(webhookSessionCookie)
		Payload(func() {
			webhookSessionPayload()
			Attribute("slug", String)
			Attribute("webhook_id", String, func() { Format(FormatUUID) })
			Attribute("search", String)
			Required("slug", "webhook_id")
		})
		Result(ArrayOf(webhookLog))
		Error("unauthenticated", webhookUnauthenticated)
		Error("forbidden", webhookForbidden)
		Error("internal_error", webhookInternal, func() { Fault() })
		HTTP(func() {
			GET("/api/workspaces/{slug}/webhook-logs/{webhook_id}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("webhook_id")
			Param("search")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("internal_error", StatusInternalServerError)
		})
	})
})

func webhookSessionPayload() {
	APIKey("webhook_session_cookie", "session_id", String)
}

func webhookFields() {
	Attribute("url", String, func() { MaxLength(1024) })
	Attribute("is_active", Boolean)
	Attribute("project", Boolean)
	Attribute("issue", Boolean)
	Attribute("module", Boolean)
	Attribute("cycle", Boolean)
	Attribute("issue_comment", Boolean)
	Attribute("is_internal", Boolean)
	Attribute("version", String, func() { MaxLength(50) })
	Attribute("created_by", String, func() { Format(FormatUUID); Nullable() })
}
