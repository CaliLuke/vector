package design

import . "github.com/CaliLuke/loom/dsl"

var workspaceHomePreference = Type("WorkspaceHomePreference", func() {
	Attribute("key", String, func() { MaxLength(255) })
	Attribute("is_enabled", Boolean)
	Attribute("sort_order", Float64)
	Required("key")
})
var workspaceHomePreferenceList = Type("WorkspaceHomePreferenceList", func() {
	Attribute("key", String, func() { MaxLength(255) })
	Attribute("is_enabled", Boolean)
	Attribute("config", Any)
	Attribute("sort_order", Float64)
	Required("key")
})
var workspaceHomePreferenceUnauthenticated = Type("WorkspaceHomePreferenceUnauthenticated", func() { Attribute("detail", String); Required("detail") })
var workspaceHomePreferenceForbidden = Type("WorkspaceHomePreferenceForbidden", func() { Attribute("detail", String); Required("detail") })
var workspaceHomePreferenceInternal = Type("WorkspaceHomePreferenceInternal", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })
var workspaceHomePreferenceNotFound = Type("WorkspaceHomePreferenceNotFound", func() {
	Attribute("detail", String, func() { Meta("struct:field:name", "Message") })
	Required("detail")
})
var workspaceHomePreferenceInvalid = Type("WorkspaceHomePreferenceInvalid", func() {
	Attribute("key", ArrayOf(String))
	Attribute("is_enabled", ArrayOf(String))
	Attribute("sort_order", ArrayOf(String))
})
var workspaceHomePreferencePatch = Type("WorkspaceHomePreferencePatch", func() {
	Attribute("key", String, func() { Nullable() })
	Attribute("is_enabled", Boolean, func() { Nullable() })
	Attribute("sort_order", Float64, func() { Nullable() })
})

var _ = Service("workspace_home_preferences", func() {
	Description("Manages workspace home preferences.")
	Method("list", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload(); Attribute("slug", String); Required("slug") })
		Result(ArrayOf(workspaceHomePreferenceList))
		Error("unauthenticated", workspaceHomePreferenceUnauthenticated)
		Error("forbidden", workspaceHomePreferenceForbidden)
		Error("internal_error", workspaceHomePreferenceInternal, func() { Fault() })
		HTTP(func() {
			GET("/api/workspaces/{slug}/home-preferences/")
			Cookie("session_id:session-id")
			Param("slug")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("patch_collection", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload(); Attribute("slug", String); Required("slug") })
		Result(ArrayOf(workspaceHomePreferenceList))
		Error("unauthenticated", workspaceHomePreferenceUnauthenticated)
		Error("forbidden", workspaceHomePreferenceForbidden)
		Error("internal_error", workspaceHomePreferenceInternal, func() { Fault() })
		HTTP(func() {
			PATCH("/api/workspaces/{slug}/home-preferences/")
			Cookie("session_id:session-id")
			Param("slug")
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("retrieve", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("slug", String)
			Attribute("key", String)
			Required("slug", "key")
		})
		Result(workspaceHomePreference)
		Error("unauthenticated", workspaceHomePreferenceUnauthenticated)
		Error("forbidden", workspaceHomePreferenceForbidden)
		Error("not_found", workspaceHomePreferenceNotFound)
		Error("internal_error", workspaceHomePreferenceInternal, func() { Fault() })
		HTTP(func() {
			GET("/api/workspaces/{slug}/home-preferences/{key}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("key")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("patch", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("slug", String)
			Attribute("key", String)
			Attribute("body", workspaceHomePreferencePatch)
			Required("slug", "key")
		})
		Result(workspaceHomePreference)
		Error("unauthenticated", workspaceHomePreferenceUnauthenticated)
		Error("forbidden", workspaceHomePreferenceForbidden)
		Error("not_found", workspaceHomePreferenceNotFound)
		Error("invalid", workspaceHomePreferenceInvalid)
		Error("internal_error", workspaceHomePreferenceInternal, func() { Fault() })
		HTTP(func() {
			PATCH("/api/workspaces/{slug}/home-preferences/{key}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("key")
			Body("body")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusBadRequest)
			Response("invalid", StatusBadRequest)
			Response("internal_error", StatusInternalServerError)
		})
	})
})
