func moduleProjectPayload() {
	stickySessionPayload()
	Attribute("slug", String)
	Attribute("project_id", String, func() { Format(FormatUUID) })
	Required("slug", "project_id")
}

func moduleScopePayload() {
	moduleProjectPayload()
	Attribute("module_id", String, func() { Format(FormatUUID) })
	Required("module_id")
}

func moduleReadErrors(notFound bool, badRequest bool) {
	Error("unauthenticated", moduleReadsUnauthenticated)
	Error("forbidden", moduleReadsForbidden)
	if notFound {
		Error("not_found", moduleReadsNotFound)
	}
	if badRequest {
		Error("bad_request", moduleReadsBadRequest)
	}
	Error("internal_error", moduleReadsInternalError, func() { Fault() })
}

func moduleReadResponses(notFound bool, badRequest bool) {
	Response("unauthenticated", StatusUnauthorized)
	Response("forbidden", StatusForbidden)
	if notFound {
		Response("not_found", StatusNotFound)
	}
	if badRequest {
		Response("bad_request", StatusBadRequest)
	}
	Response("internal_error", StatusInternalServerError)
}

func modulePermissionReadErrors(notFound bool) {
	Error("unauthenticated", moduleReadsUnauthenticated)
	Error("permission_denied", moduleReadsPermissionDenied)
	if notFound {
		Error("not_found", moduleReadsNotFound)
	}
	Error("internal_error", moduleReadsInternalError, func() { Fault() })
}

func modulePermissionReadResponses(notFound bool) {
	Response("unauthenticated", StatusUnauthorized)
	Response("permission_denied", StatusForbidden)
	if notFound {
		Response("not_found", StatusNotFound)
	}
	Response("internal_error", StatusInternalServerError)
}

