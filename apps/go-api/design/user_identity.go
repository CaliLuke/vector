package design

import . "github.com/CaliLuke/loom/dsl"

// User identity responses intentionally keep serializer-owned nested values as
// Any. The parity fixtures are the wire contract, and several of these values
// are nullable JSON objects whose shape can evolve independently of the API.
var sessionUser = Type("SessionUser", func() {
	Attribute("id", String, func() { Format(FormatUUID) })
	Attribute("avatar", String, func() { Nullable() })
	Attribute("avatar_url", String, func() { Nullable(); Meta("loom:vet:ignore", "string-format") })
	Attribute("cover_image", String, func() { Nullable() })
	Attribute("cover_image_url", String, func() { Nullable(); Meta("loom:vet:ignore", "string-format") })
	Attribute("date_joined", String, func() { Format(FormatDateTime) })
	Attribute("display_name", String)
	Attribute("email", String, func() { Nullable(); Meta("loom:vet:ignore", "string-format") })
	Attribute("first_name", String)
	Attribute("last_name", String)
	Attribute("is_active", Boolean)
	Attribute("is_bot", Boolean)
	Attribute("is_email_verified", Boolean)
	Attribute("user_timezone", String)
	Attribute("username", String)
	Attribute("is_password_autoset", Boolean)
	Attribute("last_login_medium", String, func() { Nullable() })
	Attribute("last_login_time", String, func() { Format(FormatDateTime); Nullable() })
	Required("id", "avatar", "cover_image", "date_joined", "display_name", "email", "first_name", "last_name", "is_active", "is_bot", "is_email_verified", "user_timezone", "username", "is_password_autoset", "last_login_medium", "last_login_time")
})

var userSession = Type("UserSession", func() {
	Attribute("is_authenticated", Boolean)
	Attribute("user", sessionUser, func() { Nullable() })
	Required("is_authenticated")
})

var userProfile = Type("UserProfile", func() {
	Attribute("id", String, func() { Format(FormatUUID) })
	Attribute("created_at", String, func() { Format(FormatDateTime) })
	Attribute("updated_at", String, func() { Format(FormatDateTime) })
	Attribute("theme", Any)
	Attribute("is_app_rail_docked", Boolean)
	Attribute("is_tour_completed", Boolean)
	Attribute("onboarding_step", Any)
	Attribute("use_case", String, func() { Nullable() })
	Attribute("role", String, func() { Nullable() })
	Attribute("is_onboarded", Boolean)
	Attribute("last_workspace_id", String, func() { Format(FormatUUID); Nullable() })
	Attribute("billing_address_country", String, func() { Nullable() })
	Attribute("billing_address", Any, func() { Nullable() })
	Attribute("has_billing_address", Boolean)
	Attribute("company_name", String)
	Attribute("notification_view_mode", String)
	Attribute("is_smooth_cursor_enabled", Boolean)
	Attribute("is_mobile_onboarded", Boolean)
	Attribute("mobile_onboarding_step", Any)
	Attribute("mobile_timezone_auto_set", Boolean)
	Attribute("language", String)
	Attribute("start_of_the_week", Int)
	Attribute("goals", Any)
	Attribute("background_color", String, func() { Nullable() })
	Attribute("is_navigation_tour_completed", Boolean)
	Attribute("has_marketing_email_consent", Boolean)
	Attribute("is_subscribed_to_changelog", Boolean)
	Attribute("product_tour", Any)
	Attribute("user", String, func() { Format(FormatUUID) })
	Required("id", "created_at", "updated_at", "theme", "is_app_rail_docked", "is_tour_completed", "onboarding_step", "use_case", "role", "is_onboarded", "last_workspace_id", "billing_address_country", "billing_address", "has_billing_address", "company_name", "notification_view_mode", "is_smooth_cursor_enabled", "is_mobile_onboarded", "mobile_onboarding_step", "mobile_timezone_auto_set", "language", "start_of_the_week", "goals", "background_color", "is_navigation_tour_completed", "has_marketing_email_consent", "is_subscribed_to_changelog", "product_tour", "user")
})

var userProfilePatch = Type("UserProfilePatch", func() {
	Attribute("theme", Any)
	Attribute("is_app_rail_docked", Boolean)
	Attribute("is_tour_completed", Boolean)
	Attribute("onboarding_step", Any)
	Attribute("use_case", String)
	Attribute("role", String)
	Attribute("is_onboarded", Boolean)
	Attribute("last_workspace_id", String, func() { Format(FormatUUID) })
	Attribute("billing_address_country", String)
	Attribute("billing_address", Any)
	Attribute("has_billing_address", Boolean)
	Attribute("company_name", String)
	Attribute("notification_view_mode", String)
	Attribute("is_smooth_cursor_enabled", Boolean)
	Attribute("is_mobile_onboarded", Boolean)
	Attribute("mobile_onboarding_step", Any)
	Attribute("mobile_timezone_auto_set", Boolean)
	Attribute("language", String)
	Attribute("start_of_the_week", Int)
	Attribute("goals", Any)
	Attribute("background_color", String)
	Attribute("is_navigation_tour_completed", Boolean)
	Attribute("has_marketing_email_consent", Boolean)
	Attribute("is_subscribed_to_changelog", Boolean)
	Attribute("product_tour", Any)
})

var userIdentityUnauthenticated = Type("UserIdentityUnauthenticated", func() { Attribute("detail", String); Required("detail") })
var userIdentityNotFound = Type("UserIdentityNotFound", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })
var userIdentityInternalError = Type("UserIdentityInternalError", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })
var userIdentityTimezoneNotFound = Type("UserIdentityTimezoneNotFound", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })

var _ = Service("user_identity", func() {
	Description("Returns the current session user and authenticated user's profile.")

	Method("session", func() {
		Security(planeSessionCookie)
		Security()
		Payload(func() { stickySessionPayload() })
		Result(userSession)
		Error("timezone_not_found", userIdentityTimezoneNotFound)
		Error("internal_error", userIdentityInternalError, func() { Fault() })
		HTTP(func() {
			GET("/api/users/session/")
			Cookie("session_id:session-id")
			Response(StatusOK)
			Response("timezone_not_found", StatusBadRequest)
			Response("internal_error", StatusInternalServerError)
		})
	})

	Method("me", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload() })
		Result(sessionUser)
		Error("unauthenticated", userIdentityUnauthenticated)
		Error("timezone_not_found", userIdentityTimezoneNotFound)
		Error("internal_error", userIdentityInternalError, func() { Fault() })
		HTTP(func() {
			GET("/api/users/me/")
			Cookie("session_id:session-id")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("timezone_not_found", StatusBadRequest)
			Response("internal_error", StatusInternalServerError)
		})
	})

	Method("profile", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload() })
		Result(userProfile)
		Error("unauthenticated", userIdentityUnauthenticated)
		Error("not_found", userIdentityNotFound)
		Error("internal_error", userIdentityInternalError, func() { Fault() })
		HTTP(func() {
			GET("/api/users/me/profile/")
			Cookie("session_id:session-id")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})

	Method("update_profile", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload(); Attribute("body", userProfilePatch); Required("body") })
		Result(userProfile)
		Error("unauthenticated", userIdentityUnauthenticated)
		Error("not_found", userIdentityNotFound)
		Error("internal_error", userIdentityInternalError, func() { Fault() })
		Error("invalid_json", jsonFieldValidation)
		HTTP(func() {
			PATCH("/api/users/me/profile/")
			Cookie("session_id:session-id")
			Body("body")
			Response("invalid_json", StatusBadRequest)
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
})
