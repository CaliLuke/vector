package design

import . "github.com/CaliLuke/loom/dsl"

var workspaceTheme = Type("WorkspaceTheme", func() {
	Attribute("id", String, func() { Format(FormatUUID) })
	Attribute("workspace", String, func() { Format(FormatUUID) })
	Attribute("actor", String, func() { Format(FormatUUID) })
	Attribute("created_at", String, func() { Format(FormatDateTime) })
	Attribute("updated_at", String, func() { Format(FormatDateTime) })
	Attribute("created_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("updated_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("deleted_at", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("name", String, func() { MaxLength(300) })
	Attribute("colors", Any)
	Required("id", "workspace", "actor", "created_at", "updated_at", "name", "colors")
})

var workspaceThemeUnauthenticated = Type("WorkspaceThemeUnauthenticated", func() { Attribute("detail", String); Required("detail") })
var workspaceThemeForbidden = Type("WorkspaceThemeForbidden", func() { Attribute("detail", String); Required("detail") })
var workspaceThemeNotFound = Type("WorkspaceThemeNotFound", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })
var workspaceThemeInvalid = Type("WorkspaceThemeInvalid", func() {
	Attribute("name", ArrayOf(String))
	Attribute("colors", ArrayOf(String))
})
var workspaceThemeInternal = Type("WorkspaceThemeInternal", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })

var _ = Service("workspace_themes", func() {
	Description("Manages workspace themes for active workspace members.")
	Method("list", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload(); Attribute("slug", String); Required("slug") })
		Result(ArrayOf(workspaceTheme))
		Error("unauthenticated", workspaceThemeUnauthenticated)
		Error("forbidden", workspaceThemeForbidden)
		Error("internal_error", workspaceThemeInternal, func() { Fault() })
		HTTP(func() {
			GET("/api/workspaces/{slug}/workspace-themes/")
			Cookie("session_id:session-id")
			Param("slug")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("create", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("slug", String)
			Attribute("name", String, func() { MaxLength(300) })
			Attribute("colors", Any)
			Required("slug")
		})
		Result(workspaceTheme)
		Error("unauthenticated", workspaceThemeUnauthenticated)
		Error("forbidden", workspaceThemeForbidden)
		Error("invalid", workspaceThemeInvalid)
		Error("internal_error", workspaceThemeInternal, func() { Fault() })
		HTTP(func() {
			POST("/api/workspaces/{slug}/workspace-themes/")
			Cookie("session_id:session-id")
			Param("slug")
			Response(StatusCreated)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("invalid", StatusBadRequest)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("retrieve", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Required("slug", "pk")
		})
		Result(workspaceTheme)
		Error("unauthenticated", workspaceThemeUnauthenticated)
		Error("forbidden", workspaceThemeForbidden)
		Error("not_found", workspaceThemeNotFound)
		Error("internal_error", workspaceThemeInternal, func() { Fault() })
		HTTP(func() {
			GET("/api/workspaces/{slug}/workspace-themes/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("patch", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Attribute("name", String, func() { MaxLength(300); Nullable() })
			Attribute("colors", Any, func() { Nullable() })
			Required("slug", "pk")
		})
		Result(workspaceTheme)
		Error("unauthenticated", workspaceThemeUnauthenticated)
		Error("forbidden", workspaceThemeForbidden)
		Error("not_found", workspaceThemeNotFound)
		Error("invalid", workspaceThemeInvalid)
		Error("internal_error", workspaceThemeInternal, func() { Fault() })
		HTTP(func() {
			PATCH("/api/workspaces/{slug}/workspace-themes/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("invalid", StatusBadRequest)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("delete", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Required("slug", "pk")
		})
		Error("unauthenticated", workspaceThemeUnauthenticated)
		Error("forbidden", workspaceThemeForbidden)
		Error("not_found", workspaceThemeNotFound)
		Error("internal_error", workspaceThemeInternal, func() { Fault() })
		HTTP(func() {
			DELETE("/api/workspaces/{slug}/workspace-themes/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusNoContent)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
})
