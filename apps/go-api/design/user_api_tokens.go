package design

import . "github.com/CaliLuke/loom/dsl"

var apiTokenRead = Type("APITokenRead", func() {
	Attribute("id", String, func() { Format(FormatUUID) })
	Attribute("created_at", String, func() { Format(FormatDateTime) })
	Attribute("updated_at", String, func() { Format(FormatDateTime) })
	Attribute("label", String)
	Attribute("description", String)
	Attribute("is_active", Boolean)
	Attribute("last_used", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("created_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("updated_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("deleted_at", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("user", String, func() { Format(FormatUUID) })
	Attribute("user_type", Int)
	Attribute("workspace", String, func() { Format(FormatUUID); Nullable() })
	Attribute("expired_at", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("is_service", Boolean)
	Attribute("allowed_rate_limit", String)
	Required("id", "created_at", "updated_at", "label", "description", "is_active", "user", "user_type", "is_service", "allowed_rate_limit")
})

var apiToken = Type("APIToken", func() {
	Attribute("token", String)
	Required("token")
	Attribute("id", String, func() { Format(FormatUUID) })
	Attribute("created_at", String, func() { Format(FormatDateTime) })
	Attribute("updated_at", String, func() { Format(FormatDateTime) })
	Attribute("label", String)
	Attribute("description", String)
	Attribute("is_active", Boolean)
	Attribute("last_used", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("created_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("updated_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("deleted_at", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("user", String, func() { Format(FormatUUID) })
	Attribute("user_type", Int)
	Attribute("workspace", String, func() { Format(FormatUUID); Nullable() })
	Attribute("expired_at", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("is_service", Boolean)
	Attribute("allowed_rate_limit", String)
	Required("id", "created_at", "updated_at", "label", "description", "is_active", "user", "user_type", "is_service", "allowed_rate_limit")
})

var apiTokenUnauthenticated = Type("APITokenUnauthenticated", func() { Attribute("detail", String); Required("detail") })
var apiTokenNotFound = Type("APITokenNotFound", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })
var apiTokenInternalError = Type("APITokenInternalError", func() { Attribute("error", String, func() { Meta("struct:field:name", "Message") }); Required("error") })
var apiTokenValidationError = Type("APITokenValidationError", func() { Attribute("label", ArrayOf(String)); Attribute("description", ArrayOf(String)) })

var _ = Service("user_api_tokens", func() {
	Description("Manages API tokens for the authenticated user.")
	Method("list", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload() })
		Result(ArrayOf(apiTokenRead))
		Error("unauthenticated", apiTokenUnauthenticated)
		Error("internal_error", apiTokenInternalError, func() { Fault() })
		HTTP(func() {
			GET("/api/users/api-tokens/")
			Cookie("session_id:session-id")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("create", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("label", String)
			Attribute("description", String)
			Attribute("expired_at", String, func() { Format(FormatDateTime); Nullable() })
		})
		Result(apiToken)
		Error("unauthenticated", apiTokenUnauthenticated)
		Error("internal_error", apiTokenInternalError, func() { Fault() })
		HTTP(func() {
			POST("/api/users/api-tokens/")
			Cookie("session_id:session-id")
			Response(StatusCreated)
			Response("unauthenticated", StatusUnauthorized)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("patch_collection", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload() })
		Error("unauthenticated", apiTokenUnauthenticated)
		Error("internal_error", apiTokenInternalError, func() { Fault() })
		HTTP(func() {
			PATCH("/api/users/api-tokens/")
			Cookie("session_id:session-id")
			Response("unauthenticated", StatusUnauthorized)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("delete_collection", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload() })
		Error("unauthenticated", apiTokenUnauthenticated)
		Error("internal_error", apiTokenInternalError, func() { Fault() })
		HTTP(func() {
			DELETE("/api/users/api-tokens/")
			Cookie("session_id:session-id")
			Response("unauthenticated", StatusUnauthorized)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("retrieve", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload(); Attribute("pk", String, func() { Format(FormatUUID) }); Required("pk") })
		Result(apiTokenRead)
		Error("unauthenticated", apiTokenUnauthenticated)
		Error("not_found", apiTokenNotFound)
		Error("internal_error", apiTokenInternalError, func() { Fault() })
		HTTP(func() {
			GET("/api/users/api-tokens/{pk}/")
			Cookie("session_id:session-id")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("patch", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("pk", String, func() { Format(FormatUUID) })
			Attribute("label", String)
			Attribute("description", String)
			Required("pk")
		})
		Result(apiToken)
		Error("unauthenticated", apiTokenUnauthenticated)
		Error("not_found", apiTokenNotFound)
		Error("validation", apiTokenValidationError)
		Error("internal_error", apiTokenInternalError, func() { Fault() })
		HTTP(func() {
			PATCH("/api/users/api-tokens/{pk}/")
			Cookie("session_id:session-id")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("not_found", StatusNotFound)
			Response("validation", StatusBadRequest)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("delete", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload(); Attribute("pk", String, func() { Format(FormatUUID) }); Required("pk") })
		Error("unauthenticated", apiTokenUnauthenticated)
		Error("not_found", apiTokenNotFound)
		Error("internal_error", apiTokenInternalError, func() { Fault() })
		HTTP(func() {
			DELETE("/api/users/api-tokens/{pk}/")
			Cookie("session_id:session-id")
			Response(StatusNoContent)
			Response("unauthenticated", StatusUnauthorized)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("post_detail", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload(); Attribute("pk", String, func() { Format(FormatUUID) }); Required("pk") })
		Error("unauthenticated", apiTokenUnauthenticated)
		Error("internal_error", apiTokenInternalError, func() { Fault() })
		HTTP(func() {
			POST("/api/users/api-tokens/{pk}/")
			Cookie("session_id:session-id")
			Response("unauthenticated", StatusUnauthorized)
			Response("internal_error", StatusInternalServerError)
		})
	})
})
