package design

import . "github.com/CaliLuke/loom/dsl"

var analyticView = Type("AnalyticView", func() {
	Attribute("id", String, func() { Format(FormatUUID) })
	Attribute("created_at", String, func() { Format(FormatDateTime) })
	Attribute("updated_at", String, func() { Format(FormatDateTime) })
	Attribute("created_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("updated_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("deleted_at", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("workspace", String, func() { Format(FormatUUID) })
	Attribute("name", String)
	Attribute("description", String)
	Attribute("query", Any)
	Attribute("query_dict", Any)
	Required("id", "created_at", "updated_at", "name", "description", "query", "query_dict", "workspace")
})
var analyticViewUnauthenticated = Type("AnalyticViewUnauthenticated", func() { Attribute("detail", String); Required("detail") })
var analyticViewForbidden = Type("AnalyticViewForbidden", func() { Attribute("detail", String); Required("detail") })
var analyticViewNotFound = Type("AnalyticViewNotFound", func() { Attribute("detail", String); Required("detail") })

func analyticSessionPayload() { APIKey("plane_session_cookie", "session_id", String) }

var _ = Service("analytic_views", func() {
	Method("list", func() {
		Security(planeSessionCookie)
		Payload(func() { analyticSessionPayload(); Attribute("slug", String); Required("slug") })
		Result(ArrayOf(analyticView))
		Error("unauthenticated", analyticViewUnauthenticated)
		Error("forbidden", analyticViewForbidden)
		HTTP(func() {
			GET("/api/workspaces/{slug}/analytic-view/")
			Cookie("session_id:session-id")
			Param("slug")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
		})
	})
	Method("create", func() {
		Security(planeSessionCookie)
		Payload(func() {
			analyticSessionPayload()
			Attribute("slug", String)
			Attribute("name", String)
			Attribute("description", String)
			Attribute("query_dict", Any)
			Required("slug", "name")
		})
		Result(analyticView)
		Error("unauthenticated", analyticViewUnauthenticated)
		Error("forbidden", analyticViewForbidden)
		Error("invalid_json", jsonFieldValidation)
		HTTP(func() {
			POST("/api/workspaces/{slug}/analytic-view/")
			Cookie("session_id:session-id")
			Param("slug")
			Response("invalid_json", StatusBadRequest)
			Response(StatusCreated)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
		})
	})
	Method("retrieve", func() {
		Security(planeSessionCookie)
		Payload(func() {
			analyticSessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Required("slug", "pk")
		})
		Result(analyticView)
		Error("unauthenticated", analyticViewUnauthenticated)
		Error("forbidden", analyticViewForbidden)
		Error("not_found", analyticViewNotFound)
		HTTP(func() {
			GET("/api/workspaces/{slug}/analytic-view/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
		})
	})
	Method("patch", func() {
		Security(planeSessionCookie)
		Payload(func() {
			analyticSessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Attribute("name", String)
			Attribute("description", String)
			Attribute("query_data", Any)
			Required("slug", "pk")
		})
		Result(analyticView)
		Error("unauthenticated", analyticViewUnauthenticated)
		Error("forbidden", analyticViewForbidden)
		Error("not_found", analyticViewNotFound)
		HTTP(func() {
			PATCH("/api/workspaces/{slug}/analytic-view/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
		})
	})
	Method("delete", func() {
		Security(planeSessionCookie)
		Payload(func() {
			analyticSessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Required("slug", "pk")
		})
		Error("unauthenticated", analyticViewUnauthenticated)
		Error("forbidden", analyticViewForbidden)
		Error("not_found", analyticViewNotFound)
		HTTP(func() {
			DELETE("/api/workspaces/{slug}/analytic-view/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusNoContent)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
		})
	})
})
