var userPropertiesUnauthenticated = Type("UserPropertiesUnauthenticated", func() {
	Attribute("detail", String)
	Required("detail")
})
var userPropertiesForbidden = Type("UserPropertiesForbidden", func() {
	Attribute("error", String, func() { Meta("struct:field:name", "Message") })
	Required("error")
})
var userPropertiesNotFound = Type("UserPropertiesNotFound", func() {
	Attribute("detail", String, func() { Meta("struct:field:name", "Message") })
	Required("detail")
})
var userPropertiesInternal = Type("UserPropertiesInternal", func() {
	Attribute("error", String, func() { Meta("struct:field:name", "Message") })
	Required("error")
})

func userPropertiesSessionPayload() {
	APIKey("plane_session_cookie", "session_id", String)
}

func userPropertiesPayload() {
	userPropertiesSessionPayload()
	Attribute("slug", String)
	Required("slug")
}

