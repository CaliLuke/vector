package design

import . "github.com/CaliLuke/loom/dsl"

var workspaceQuickLink = Type("WorkspaceQuickLink", func() {
	Attribute("id", String, func() { Format(FormatUUID) })
	Attribute("created_at", String, func() { Format(FormatDateTime) })
	Attribute("updated_at", String, func() { Format(FormatDateTime) })
	Attribute("created_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("updated_by", String, func() { Format(FormatUUID); Nullable() })
	Attribute("deleted_at", String, func() { Format(FormatDateTime); Nullable() })
	Attribute("workspace", String, func() { Format(FormatUUID) })
	Attribute("project", String, func() { Format(FormatUUID); Nullable() })
	Attribute("owner", String, func() { Format(FormatUUID) })
	Attribute("title", String, func() { Nullable() })
	Attribute("url", String, func() { Format(FormatURI) })
	Attribute("metadata", Any)
	Required("id", "created_at", "updated_at", "workspace", "owner", "url", "metadata")
})

var workspaceQuickLinkUnauthenticated = Type("WorkspaceQuickLinkUnauthenticated", func() {
	Attribute("detail", String)
	Required("detail")
})
var workspaceQuickLinkForbidden = Type("WorkspaceQuickLinkForbidden", func() {
	Attribute("detail", String)
	Required("detail")
})
var workspaceQuickLinkRetrieveNotFound = Type("WorkspaceQuickLinkRetrieveNotFound", func() {
	Attribute("error", String, func() { Meta("struct:field:name", "Message") })
	Required("error")
})
var workspaceQuickLinkPatchNotFound = Type("WorkspaceQuickLinkPatchNotFound", func() {
	Attribute("detail", String)
	Required("detail")
})
var workspaceQuickLinkDeleteNotFound = Type("WorkspaceQuickLinkDeleteNotFound", func() {
	Attribute("error", String, func() { Meta("struct:field:name", "Message") })
	Required("error")
})
var workspaceQuickLinkURLValidationDetail = Type("WorkspaceQuickLinkURLValidationDetail", func() {
	Attribute("error", String, func() { Meta("struct:field:name", "Message") })
	Required("error")
})
var workspaceQuickLinkValidation = Type("WorkspaceQuickLinkValidation", func() {
	Attribute("url", workspaceQuickLinkURLValidationDetail)
	Attribute("metadata", ArrayOf(String))
})
var workspaceQuickLinkInternal = Type("WorkspaceQuickLinkInternal", func() {
	Attribute("error", String, func() { Meta("struct:field:name", "Message") })
	Required("error")
})

var _ = Service("workspace_quick_links", func() {
	Description("Manages user-owned quick links in a workspace.")
	Method("list", func() {
		Security(planeSessionCookie)
		Payload(func() { stickySessionPayload(); Attribute("slug", String); Required("slug") })
		Result(ArrayOf(workspaceQuickLink))
		Error("unauthenticated", workspaceQuickLinkUnauthenticated)
		Error("forbidden", workspaceQuickLinkForbidden)
		Error("internal_error", workspaceQuickLinkInternal, func() { Fault() })
		HTTP(func() {
			GET("/api/workspaces/{slug}/quick-links/")
			Cookie("session_id:session-id")
			Param("slug")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("create", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("slug", String)
			Attribute("title", String, func() { Nullable() })
			Attribute("url", String, func() { Meta("loom:vet:ignore", "string-format") })
			Attribute("metadata", Any)
			Required("slug", "url")
		})
		Result(workspaceQuickLink)
		Error("unauthenticated", workspaceQuickLinkUnauthenticated)
		Error("forbidden", workspaceQuickLinkForbidden)
		Error("validation", workspaceQuickLinkValidation)
		Error("internal_error", workspaceQuickLinkInternal, func() { Fault() })
		HTTP(func() {
			POST("/api/workspaces/{slug}/quick-links/")
			Cookie("session_id:session-id")
			Param("slug")
			Response(StatusCreated)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("validation", StatusBadRequest)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("retrieve", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Required("slug", "pk")
		})
		Result(workspaceQuickLink)
		Error("unauthenticated", workspaceQuickLinkUnauthenticated)
		Error("forbidden", workspaceQuickLinkForbidden)
		Error("not_found", workspaceQuickLinkRetrieveNotFound)
		Error("internal_error", workspaceQuickLinkInternal, func() { Fault() })
		HTTP(func() {
			GET("/api/workspaces/{slug}/quick-links/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("patch", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Attribute("title", String, func() { Nullable() })
			Attribute("url", String, func() { Meta("loom:vet:ignore", "string-format") })
			Attribute("metadata", Any)
			Required("slug", "pk")
		})
		Result(workspaceQuickLink)
		Error("unauthenticated", workspaceQuickLinkUnauthenticated)
		Error("forbidden", workspaceQuickLinkForbidden)
		Error("not_found", workspaceQuickLinkPatchNotFound)
		Error("validation", workspaceQuickLinkValidation)
		Error("internal_error", workspaceQuickLinkInternal, func() { Fault() })
		HTTP(func() {
			PATCH("/api/workspaces/{slug}/quick-links/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusOK)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("validation", StatusBadRequest)
			Response("internal_error", StatusInternalServerError)
		})
	})
	Method("delete", func() {
		Security(planeSessionCookie)
		Payload(func() {
			stickySessionPayload()
			Attribute("slug", String)
			Attribute("pk", String, func() { Format(FormatUUID) })
			Required("slug", "pk")
		})
		Error("unauthenticated", workspaceQuickLinkUnauthenticated)
		Error("forbidden", workspaceQuickLinkForbidden)
		Error("not_found", workspaceQuickLinkDeleteNotFound)
		Error("internal_error", workspaceQuickLinkInternal, func() { Fault() })
		HTTP(func() {
			DELETE("/api/workspaces/{slug}/quick-links/{pk}/")
			Cookie("session_id:session-id")
			Param("slug")
			Param("pk")
			Response(StatusNoContent)
			Response("unauthenticated", StatusUnauthorized)
			Response("forbidden", StatusForbidden)
			Response("not_found", StatusNotFound)
			Response("internal_error", StatusInternalServerError)
		})
	})
})
