import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import test from "node:test";

const script = fileURLToPath(new URL("./go-source-files.mjs", import.meta.url));

void test("source discovery retains the exact generated-header boundary", (t) => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "go-source-files-"));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const marker = "// Code generated by a tool. DO NOT EDIT.";
  const fixtures = {
    "owned.go": "package owned\n",
    "empty.go": "",
    "space name.go": "package owned\n",
    "generated.go": marker + "\npackage generated\n",
    "line-ten.go": "\n".repeat(9) + marker,
    "line-eleven.go": "\n".repeat(10) + marker,
    "crlf.go": marker + "\r\n",
    "indented.go": " " + marker,
    "trailing.go": marker + " extra",
  };
  for (const [name, source] of Object.entries(fixtures)) fs.writeFileSync(path.join(directory, name), source);
  const result = spawnSync(process.execPath, [script], {
    cwd: directory,
    input: Object.keys(fixtures).join("\0") + "\0",
    encoding: "utf8",
  });
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(result.stdout.trimEnd().split("\n"), [
    "owned.go",
    "empty.go",
    "space name.go",
    "line-eleven.go",
    "crlf.go",
    "indented.go",
    "trailing.go",
  ]);
});

void test("source discovery fails when an inventoried file cannot be read", () => {
  const result = spawnSync(process.execPath, [script], { input: "/nonexistent-vector-source.go\0", encoding: "utf8" });
  assert.notEqual(result.status, 0);
  assert.equal(result.stdout, "");
});
