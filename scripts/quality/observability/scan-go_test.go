package main

import (
	"reflect"
	"regexp"
	"strings"
	"testing"
)

func TestScanGo(t *testing.T) {
	const body = `package fixture
import (
    "context"
    "errors"
    "fmt"
    "log/slog"
    netHTTP "net/http"
    "github.com/CaliLuke/loom/clue/log"
    api "example.test/project/gen/account"
)

type service struct{}

func (*service) internal() error {
    return &api.AccountInternalError{}
}

func (s *service) handle(ctx context.Context, response netHTTP.ResponseWriter, err, otherErr error) error {
    if errors.Is(err, context.Canceled) { return nil }
    if err != nil {
        if err == context.Canceled {
            response.WriteHeader(netHTTP.StatusInternalServerError)
            return nil
        }
        if err == ErrForbidden { return serviceError(403) }
        if err == ErrMissing { return serviceError(404) }
        return s.internal() // want unclassified-server-failure
    }
    if nil != otherErr {
        slog.WarnContext(ctx, "operation failed")
        return serviceError(netHTTP.StatusServiceUnavailable) // want weak-server-failure-diagnostic
    }
    return fmt.Errorf("operation failed: %w", err)
}

func emit(ctx context.Context, response netHTTP.ResponseWriter, err error) {
    if err != nil && errors.Is(err, context.Canceled) {
        netHTTP.Error(response, "retry", netHTTP.StatusServiceUnavailable)
        return
    }
    if err != nil && !errors.Is(err, ErrMissing) {
        netHTTP.Error(response, "retry", netHTTP.StatusServiceUnavailable) // want unclassified-server-failure
    }
    if err != nil {
        log.Error(ctx, nil, log.KV{K: "msg", V: "missing cause"})
        response.WriteHeader(502) // want weak-server-failure-diagnostic
    }
    if err != nil {
        slog.ErrorContext(ctx, "repository read failed", "error", err)
        response.WriteHeader(netHTTP.StatusInternalServerError)
    }
    if err != nil {
        logPublicProjectMetadataCompatibilityError(ctx, err)
        response.WriteHeader(netHTTP.StatusInternalServerError)
    }
}

func report(ctx context.Context, err error, retry bool) error {
    if err != nil {
        if retry {
            workItemLogError(ctx, "operation", "stage", err)
            return serviceError(503)
        }
        return serviceError(500) // want unclassified-server-failure
    }
    if err != nil {
        if retry { workItemLogError(ctx, "other branch", "stage", err) }
        go func() { workItemLogError(ctx, "closure", "stage", err) }()
        return serviceError(500) // want unclassified-server-failure
    }
    if err != nil {
        return serviceError(422)
    }
    if err != nil {
        return fmt.Errorf("propagated: %w", err)
    }
    return nil
}
`
	findings, err := scan("fixture.go", body)
	if err != nil {
		t.Fatal(err)
	}
	re := regexp.MustCompile(`// want ([a-z-]+)$`)
	want := map[int]string{}
	for index, line := range strings.Split(body, "\n") {
		if annotation := re.FindStringSubmatch(line); len(annotation) > 0 {
			want[index+1] = annotation[1]
		}
	}
	got := map[int]string{}
	for _, finding := range findings {
		if _, duplicate := got[finding.Line]; duplicate || finding.File != "fixture.go" || finding.Column < 1 || finding.Message == "" {
			t.Fatalf("invalid finding: %+v", finding)
		}
		got[finding.Line] = finding.Rule
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("scan findings = %v, want %v", got, want)
	}
}

func TestScanGoSkipsGeneratedAndReturnsParseErrors(t *testing.T) {
	generated := `// Code generated by fixture. DO NOT EDIT.
package fixture
func run(err error) (int, string) {
	if err != nil { return 500, "failure" }
	return 200, ""
}`
	if findings, err := scan("generated.go", generated); err != nil || len(findings) != 0 {
		t.Fatalf("generated input: findings %v, error %v", findings, err)
	}
	if _, err := scan("bad.go", "package bad\nfunc"); err == nil {
		t.Fatal("expected parse failure")
	}
}
